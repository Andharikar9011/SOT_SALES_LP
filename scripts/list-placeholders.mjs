// Generates ../CONTENT_TODO.md listing every [PLACEHOLDER] value in public/data/content.json
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const content = JSON.parse(fs.readFileSync(new URL('public/data/content.json', root), 'utf8'));
const rows = [];

function walk(node, path) {
  if (typeof node === 'string') {
    if (node.includes('[PLACEHOLDER]')) rows.push([path, node]);
  } else if (Array.isArray(node)) {
    node.forEach((v, i) => walk(v, `${path}[${i}]`));
  } else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) walk(v, path ? `${path}.${k}` : k);
  }
}
walk(content, '');

const hint = (p) => {
  if (/calendlyUrl/.test(p)) return 'Your real Calendly event link (https://calendly.com/<user>/<event>)';
  if (/fees\.amount/.test(p)) return 'Real program fee, e.g. the rupee amount';
  if (/fees\.note/.test(p)) return 'Real scholarship / EMI terms';
  if (/outcomes\.note/.test(p)) return 'Verified placement figures (or leave as a neutral note)';
  if (/faq\[\d+\]\.answer/.test(p)) return 'Verified answer / confirmed policy text';
  if (/mentors\[\d+\]\.name/.test(p)) return 'Mentor full name (real, consented)';
  if (/mentors\[\d+\]\.company/.test(p)) return 'Mentor current company';
  if (/mentors\[\d+\]\.bio/.test(p)) return 'Short factual bio';
  if (/mentors\[\d+\]\.imageAlt/.test(p)) return 'Alt text describing the mentor photo';
  if (/mentors\[\d+\]\.schedule/.test(p)) return 'Real session schedule';
  if (/companies\[\d+\]\.name/.test(p)) return 'Real hiring partner name (with permission)';
  if (/companies\[\d+\]\.alt/.test(p)) return 'Alt text, e.g. "<Company> logo"';
  if (/placedCard/.test(p)) return 'Real example placement (or remove the card content)';
  if (/uiPlaceholder|companiesHeading/.test(p)) return 'Final heading for the hiring partners row';
  return 'Supply the real value';
};

const esc = (s) => s.replace(/\|/g, '\\|');
let md = '# CONTENT TODO\n\n';
md += 'Generated by `npm run todo` (app/scripts/list-placeholders.mjs) from `app/public/data/content.json`.\n';
md += 'Replace every value below, then re-run `npm run todo` (the list should become empty).\n\n';
md += `Total placeholders: **${rows.length}**\n\n`;
md += '| # | Key path | Current value | What to supply |\n|---|---|---|---|\n';
rows.forEach(([p, v], i) => { md += `| ${i + 1} | \`${p}\` | ${esc(v)} | ${hint(p)} |\n`; });
md += '\n## Also not placeholders but still to do\n\n';
md += '- `images.logo`, `images.companies[*].src`, `mentors[*].image`: replace the neutral placeholder SVGs in `app/public/images/` (or point the JSON at real URLs).\n';
md += '- `site.ogImage` points to `/images/og-image.png`, which does not exist yet. Add a 1200x630 image.\n';
md += '- `form.submitEndpoint` is empty (demo mode: nothing is sent). Set it to a real endpoint to receive applications.\n';
md += '- `footer.social[*].href` are empty; those links are hidden until filled. Legal pages (`/privacy`, `/terms`, `/refund`) do not exist yet.\n';
md += '- Theme colors are a placeholder palette; after changing them run `npm run check:theme`.\n';

const out = fileURLToPath(new URL('../CONTENT_TODO.md', root));
fs.writeFileSync(out, md);
console.log(`Wrote ${out} (${rows.length} placeholders)`);
